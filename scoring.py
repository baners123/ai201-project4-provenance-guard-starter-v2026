"""Combine Provenance Guard signals and map scores to reader-facing labels."""

import config


def _clip01(value: float) -> float:
    return min(max(float(value), 0.0), 1.0)


def combine_signals(model_score: float, style_score: float) -> float:
    """Combine two 0 to 1 AI-likelihood scores.

    The local model signal receives 65 percent of the weight and the
    stylometry signal receives 35 percent.
    """
    total_weight = config.WEIGHT_MODEL_SIGNAL + config.WEIGHT_STYLE_SIGNAL
    if total_weight <= 0:
        raise ValueError("Signal weights must add to a positive number.")

    combined = (
        config.WEIGHT_MODEL_SIGNAL * _clip01(model_score)
        + config.WEIGHT_STYLE_SIGNAL * _clip01(style_score)
    ) / total_weight

    return round(_clip01(combined), 4)


def score_to_label(score: float) -> tuple[str, str]:
    """Map a combined score to a machine guess and reader-facing label."""
    score = _clip01(score)

    if score >= config.AI_THRESHOLD:
        return (
            "ai",
            "This text shows strong signs of AI generation, but this result "
            "is not proof of authorship. The writer can appeal this decision "
            "for review.",
        )

    if score <= config.HUMAN_THRESHOLD:
        return (
            "human",
            "We think this was probably written by a person.",
        )

    return (
        "unsure",
        "We are not confident enough to say whether this was written by a "
        "person or generated by AI. No action should be taken based on this "
        "result alone.",
    )


def label_ranges() -> list[tuple[str, str]]:
    """Return the configured score range for each label."""
    return [
        ("high-confidence human", f"0.00 - {config.HUMAN_THRESHOLD:.2f}"),
        ("unsure", f"{config.HUMAN_THRESHOLD:.2f} - {config.AI_THRESHOLD:.2f}"),
        ("high-confidence AI", f"{config.AI_THRESHOLD:.2f} - 1.00"),
    ]


if __name__ == "__main__":
    for name, band in label_ranges():
        print(f"{name}: {band}")

    for sample in (0.15, 0.51, 0.92):
        guess, label = score_to_label(sample)
        print(f"{sample:.2f}: {guess} | {label}")
